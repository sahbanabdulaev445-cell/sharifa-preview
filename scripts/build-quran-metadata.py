"""Convert the checked-in Tanzil metadata to a compact offline TypeScript catalog."""
from pathlib import Path
import json
root=Path(__file__).resolve().parents[1]
m=json.loads((root/'lib/quran-metadata.json').read_text(encoding='utf8'))
names='Аль-Фатиха|Аль-Бакара|Аль Имран|Ан-Ниса|Аль-Маида|Аль-Анам|Аль-Араф|Аль-Анфаль|Ат-Тауба|Юнус|Худ|Юсуф|Ар-Рад|Ибрахим|Аль-Хиджр|Ан-Нахль|Аль-Исра|Аль-Кахф|Марьям|Та Ха|Аль-Анбия|Аль-Хаджж|Аль-Муминун|Ан-Нур|Аль-Фуркан|Аш-Шуара|Ан-Намль|Аль-Касас|Аль-Анкабут|Ар-Рум|Лукман|Ас-Саджда|Аль-Ахзаб|Саба|Фатыр|Я Син|Ас-Саффат|Сад|Аз-Зумар|Гафир|Фуссылат|Аш-Шура|Аз-Зухруф|Ад-Духан|Аль-Джасия|Аль-Ахкаф|Мухаммад|Аль-Фатх|Аль-Худжурат|Каф|Аз-Зарият|Ат-Тур|Ан-Наджм|Аль-Камар|Ар-Рахман|Аль-Вакиа|Аль-Хадид|Аль-Муджадиля|Аль-Хашр|Аль-Мумтахана|Ас-Сафф|Аль-Джумуа|Аль-Мунафикун|Ат-Тагабун|Ат-Таляк|Ат-Тахрим|Аль-Мульк|Аль-Калам|Аль-Хакка|Аль-Мааридж|Нух|Аль-Джинн|Аль-Муззаммиль|Аль-Муддассир|Аль-Кыяма|Аль-Инсан|Аль-Мурсалят|Ан-Наба|Ан-Назиат|Абаса|Ат-Таквир|Аль-Инфитар|Аль-Мутаффифин|Аль-Иншикак|Аль-Бурудж|Ат-Тарик|Аль-Аля|Аль-Гашия|Аль-Фаджр|Аль-Баляд|Аш-Шамс|Аль-Ляйль|Ад-Духа|Аш-Шарх|Ат-Тин|Аль-Аляк|Аль-Кадр|Аль-Баййина|Аз-Зальзаля|Аль-Адият|Аль-Кариа|Ат-Такасур|Аль-Аср|Аль-Хумаза|Аль-Филь|Курайш|Аль-Маун|Аль-Каусар|Аль-Кафирун|Ан-Наср|Аль-Масад|Аль-Ихляс|Аль-Фаляк|Ан-Нас'.split('|')
assert len(names)==len(m['suras'])==114
catalog=[{'id':int(a['index']),'name':names[i],'arabic':a['name'],'verses':int(a['ayas']),'start':int(a['start'])} for i,a in enumerate(m['suras'])]
juzs=[{'juz':int(a['index']),'surah':int(a['sura']),'ayah':int(a['aya'])} for a in m['juzs']]
text='''// Generated by scripts/build-quran-metadata.py.
// Verse counts, Arabic names and juz boundaries: Tanzil Project, metadata v1.0.
// https://tanzil.net/docs/Quran_Metadata
// https://tanzil.net/res/text/metadata/quran-data.xml
// Russian transliterations are display labels. No Quran verse text is included.
export type Surah={id:number;name:string;arabic:string;verses:number;start:number};
export const surahs:Surah[]=CATALOG;
export const juzStarts=JUZS;
export type StudiedMaterial={juz:number;surah:number;wholeSurah:boolean;fromAyah?:number;toAyah?:number};
export const surahById=(id:number)=>surahs.find(s=>s.id===id);
export function juzForAyah(surah:number,ayah:number){let found=1;for(const start of juzStarts)if(start.surah<surah||start.surah===surah&&start.ayah<=ayah)found=start.juz;return found}
export function surahRangeInJuz(surah:number,juz:number){
 const s=surahById(surah),a=juzStarts[juz-1],b=juzStarts[juz];if(!s||!a)return null;
 const first=surah<a.surah?s.verses+1:surah===a.surah?a.ayah:1;
 const last=b?(surah>b.surah?0:surah===b.surah?b.ayah-1:s.verses):s.verses;
 return first<=last?{from:first,to:last}:null;
}
export function materialLabel(material:StudiedMaterial|undefined){
 if(!material)return "Материал не указан";
 const s=surahById(material.surah);
 return `Джуз ${material.juz} · ${material.surah} — ${s?.name??"Сура"} · ${material.wholeSurah?"вся сура":`аяты ${material.fromAyah}–${material.toAyah}`}`;
}
'''.replace('CATALOG',json.dumps(catalog,ensure_ascii=False,separators=(',',':'))).replace('JUZS',json.dumps(juzs,separators=(',',':')))
(root/'lib/quran.ts').write_text(text,encoding='utf8')
