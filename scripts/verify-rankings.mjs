// Isolated calculations: no browser storage or user records are accessed.
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import {createRequire} from "node:module";
import ts from "typescript";
const nativeRequire=createRequire(import.meta.url),cache=new Map();
function load(file){
 const filename=path.resolve(file);if(cache.has(filename))return cache.get(filename).exports;
 const module={exports:{}};cache.set(filename,module);
 const code=ts.transpileModule(fs.readFileSync(filename,"utf8"),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
 const require=name=>name.startsWith(".")?load(path.resolve(path.dirname(filename),name)+".ts"):nativeRequire(name);
 new Function("require","module","exports",code)(require,module,module.exports);return module.exports;
}
const model=load("lib/analytics.ts"),{groupRankings,branchRankings}=load("lib/rankings.ts");
const data=structuredClone(model.emptyData),period="2026-10";
const teacher=(id,name,gender,branch)=>({id,name,gender,branch,kind:"teacher",groups:"",startDate:"2026-01-01"});
const male=teacher("male","Ахмад","male","Первый"),female=teacher("female","Аиша","female","Первый"),other=teacher("other","Фатима","female","Второй");
const group=(id,name,t)=>({id,name,teacherId:t.id,branch:t.branch,gender:"male",days:[0],startTime:"09:00",endTime:"10:00"});
const shared=group("shared","Общая",male),small=group("small","Заучивание",female),second=group("second","Чтение",other),empty=group("empty","Без проверок",male);
female.groupAssignments=[shared,small].map(g=>({groupId:g.id,days:g.days,startTime:g.startTime,endTime:g.endTime}));
const pupil=(id,g)=>({id,name:id,kind:"student",gender:"male",branch:g.branch,teacherId:g.teacherId,groupId:g.id,groups:g.name,age:10,level:"Начальный",startDate:"2026-01-01"});
const pupils=[pupil("one",shared),pupil("two",small),pupil("three",small),pupil("four",second),pupil("unrated",shared),{...pupil("archived",shared),archived:true}];
data.people=[male,female,other,...pupils];data.groups=[shared,small,second,empty];
const check=(id,personId,date,makhraj,tajweed,hifz)=>({id,personId,date,makhraj,tajweed,...(hifz===undefined?{}:{hifz}),assessmentType:"reading",readingMode:"quran",groupId:pupils.find(p=>p.id===personId)?.groupId,teacherId:pupils.find(p=>p.id===personId)?.teacherId,note:""});
data.checks=[check("old","one","2026-09-01",1,1),check("new","one","2026-10-01",10,10),check("two","two","2026-10-01",1,2,3),check("three","three","2026-10-01",2,2),check("four","four","2026-10-01",10,10),check("archived","archived","2026-10-01",1,1)];
const filters={branch:"all",teacherGender:"all",teacherId:"all",search:""};
let rows=groupRankings(data,period,filters);
assert.equal(rows.length,4,"Shared groups appear once even when multiple teachers teach them");
assert.deepEqual(rows.map(row=>row.rank),[1,1,3,null],"Tied scores share a place; unassessed groups have no place");
assert.equal(rows.find(row=>row.group.id===shared.id).score,10,"Latest period score, excluding archived and unassessed students");
assert.equal(rows.find(row=>row.group.id===shared.id).students.length,2);
assert.equal(rows.find(row=>row.group.id===shared.id).assessed,1);
assert.equal(rows.find(row=>row.group.id===small.id).score,2,"Reading result includes hifz when assessed");
assert.equal(rows.find(row=>row.group.id===empty.id).score,null);
assert.deepEqual(groupRankings(data,period,{...filters,teacherGender:"male"}).map(row=>row.group.id),[shared.id,empty.id]);
rows=groupRankings(data,period,{...filters,teacherGender:"female",branch:"Первый"});
assert.equal(rows.length,2,"Teacher gender does not filter by students' gender");
assert.deepEqual(rows.find(row=>row.group.id===shared.id).teachers.map(t=>t.id),[female.id]);
assert.equal(groupRankings(data,period,{...filters,teacherId:female.id}).length,2);
assert.equal(groupRankings(data,period,{...filters,teacherGender:"male",teacherId:female.id}).length,0);
assert.equal(groupRankings(data,period,{...filters,search:"  аИшА  "}).length,2);
assert.equal(groupRankings(data,period,{...filters,search:"второй"}).length,1);
assert.equal(groupRankings(data,"2026-08",filters).every(row=>row.score===null&&row.rank===null),true);
assert.equal(groupRankings(data,"2026-09",filters).find(row=>row.group.id===shared.id).score,1);
const branches=branchRankings(data,period,filters);
assert.equal(branches[0].name,"Второй");
const first=branches.find(row=>row.name==="Первый");
assert.equal(first.score,14/3,"Branch result averages assessed students rather than groups of unequal sizes");
assert.equal(first.assessed,3);assert.equal(first.students.length,4);assert.equal(first.groups,3);assert.equal(first.teachers.length,2);
assert.equal(branchRankings(data,period,{...filters,teacherGender:"male"})[0].score,10);
assert.equal(branchRankings(data,period,{...filters,branch:"Первый"}).length,1);
assert.equal(branchRankings(data,period,{...filters,search:"  ВТОРОЙ "})[0].name,"Второй");
assert.deepEqual(groupRankings(model.emptyData,period,filters),[]);
assert.deepEqual(branchRankings(model.emptyData,period,filters),[]);
const archivedTeacher={...data,people:data.people.map(p=>p.id===other.id?{...p,archived:true}:p)};
assert.equal(groupRankings(archivedTeacher,period,filters).some(row=>row.group.id===second.id),false);
console.log("PASS: group and branch rankings, latest period scores, teacher gender/branch/search filters, shared groups, ties, unassessed/archived students and student-weighted branch results.");
