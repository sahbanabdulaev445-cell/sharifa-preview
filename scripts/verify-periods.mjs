import assert from "node:assert/strict";
import fs from "node:fs";
import ts from "typescript";

const compiled=ts.transpileModule(fs.readFileSync("lib/analytics.ts","utf8"),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const model=await import("data:text/javascript;base64,"+Buffer.from(compiled).toString("base64"));
const {inPeriod,periodBounds,chartMonths,latest,result,delta,alerts,compareChecks,emptyData}=model;
assert.deepEqual(periodBounds("2024-02"),{start:"2024-02-01",end:"2024-02-29"});
assert.deepEqual(periodBounds("2026"),{start:"2026-01-01",end:"2026-12-31"});
for(const date of ["2026-01-01","2026-12-31"])assert.equal(inPeriod(date,"2026"),true);
for(const date of ["2025-12-31","2027-01-01"])assert.equal(inPeriod(date,"2026"),false);
const range="range:2025-12-31:2026-01-02";
for(const date of ["2025-12-31","2026-01-01","2026-01-02"])assert.equal(inPeriod(date,range),true);
for(const date of ["2025-12-30","2026-01-03"])assert.equal(inPeriod(date,range),false);
assert.equal(inPeriod("2026-03-01","range:2026-03-01:2026-03-01"),true);
assert.equal(inPeriod("2026-03-02","range:2026-03-01:2026-03-01"),false);
const data=structuredClone(emptyData);
const teacher={id:"teacher",kind:"teacher",name:"Teacher",gender:"male",branch:"Гамидова",groups:"A",startDate:"2020-01-01"};
const student={...teacher,id:"student",kind:"student",teacherId:teacher.id};
data.people=[teacher,student];
const check=(id,personId,date,score,createdAt)=>({id,personId,date,makhraj:score,tajweed:score,hifz:score,attendance:score,note:"",createdAt});
data.checks=[check("t-dec",teacher.id,"2025-12-31",8),check("t-jan",teacher.id,"2026-01-01",6),check("s-jan",student.id,"2026-01-02",5),check("t-next",teacher.id,"2027-01-01",9)];
assert.equal(latest(data,teacher.id,"2026").id,"t-jan");
assert.equal(latest(data,teacher.id,range).id,"t-jan");
assert.equal(latest(data,teacher.id,"2026-02"),null);
assert.equal(result(data,teacher,"2026"),5.8);
assert.equal(delta(data,teacher,"2026"),-2.2);
assert.ok(alerts(data,teacher,"2026").some(message=>message.includes("снижение")));
assert.deepEqual(chartMonths(data,"2026"),Array.from({length:12},(_,i)=>`2026-${String(i+1).padStart(2,"0")}`));
assert.deepEqual(chartMonths(data,range),["2025-12","2026-01"]);
assert.deepEqual(chartMonths(data,"range:2026-10-03:2026-10-03"),["2026-10"]);
assert.equal(chartMonths(emptyData,"all").length,6);
const events=[check("a","a","2026-10-02",5),check("b","b","2026-10-04",5,"2026-10-04T08:00:00Z"),check("c","c","2026-10-04",5,"2026-10-04T10:00:00Z")];
assert.deepEqual(events.sort(compareChecks).slice(0,2).map(c=>c.id),["c","b"]);
const newer=check("d",teacher.id,"2026-01-01",7,"2026-01-01T12:00:00Z");
data.checks.push(newer);
assert.equal(latest(data,teacher.id,"2026").id,"d");
assert.equal(result(emptyData,teacher,"2026"),null);
assert.deepEqual(alerts(emptyData,teacher,"2026"),[]);
console.log("PASS: inclusive date ranges, calendar years, leap years, empty periods, ratings, monthly decline, chronological attention, and chart months.");
